#!/usr/bin/env python3
"""手動で画像を作る用のプロンプト（4コマ漫画）を出力する。
ChatGPT / Geminiアプリに assets/character_ref.png を添付して、出力をそのまま貼る。

使い方: python3 scripts/make_image_prompt.py "投稿文"
"""
import sys

STYLE = (
    "添付した画像の人物を主人公にした「4コマ漫画」を、縦長（2:3）の1枚の画像で描いてください。\n"
    "人物の特徴: オレンジ色のふんわりした髪、にこやかな笑顔、頬に淡いピンクの丸、白シャツに紺のネクタイ、青い作業着（胸に小さな名札、胸ポケットにペン）。\n"
    "- 縦に4コマを並べる。コマの間は白い余白で区切る\n"
    "- 4コマの流れ: 1コマ目=状況、2コマ目=展開、3コマ目=転換、4コマ目=オチ（クスッと笑える、またはハッとする）\n"
    "- 4コマすべてに同じ人物が登場し、顔・髪色・服装をそろえる\n"
    "- 絵柄は添付画像と同じ、やわらかい水彩風のイラスト。線は細め\n"
    "- 舞台は製造業の現場（工作機械、生産計画のボードなど）\n"
    "- 吹き出しや文字・数字は入れない（表情と絵で伝える。名札は無地のままでよい）\n"
    "- 安全に関わる場面では保護具（保護メガネ・ヘルメット）を着用させる"
)

if len(sys.argv) < 2:
    sys.exit('使い方: make_image_prompt.py "投稿文"')
print(f"{STYLE}\n\nネタ: 次のX投稿の内容を4コマにしてください。画像は1枚だけ生成してください。\n「{sys.argv[1]}」")
