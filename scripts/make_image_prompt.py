#!/usr/bin/env python3
"""手動で画像を作る用のプロンプトを出力する。
Geminiアプリ / ChatGPT に assets/icon.png を添付して、出力をそのまま貼る。

使い方: python3 scripts/make_image_prompt.py "投稿文"
"""
import sys

STYLE = (
    "添付した画像の人物を主人公にしたイラストを描いてください。\n"
    "人物の特徴: オレンジ色のふんわりした髪、にこやかな笑顔、頬に淡いピンクの丸、白シャツに紺のネクタイ、青い作業着（胸に小さな名札、胸ポケットにペン）。\n"
    "- 絵柄は添付画像と同じ、やわらかい水彩風のイラスト。線は細め、正方形（1:1）\n"
    "- 舞台は製造業の現場（工作機械、生産計画のボードなど）\n"
    "- 画像の中に文字や数字は入れない（名札は無地のままでよい）\n"
    "- 安全に関わる場面では保護具（保護メガネ・ヘルメット）を着用させる"
)

if len(sys.argv) < 2:
    sys.exit('使い方: make_image_prompt.py "投稿文"')
print(f"{STYLE}\n\n場面: 次のX投稿の内容を、見た人が思わずクスッと・ハッとする1場面で表現してください。\n構図・ポーズ・背景を変えた3パターンを、別々の画像として3枚生成してください。\n「{sys.argv[1]}」")
